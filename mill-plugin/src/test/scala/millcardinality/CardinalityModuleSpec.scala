package millcardinality

import mainargs.Leftover
import mill.*
import mill.api.Discover
import mill.testkit.{TestRootModule, UnitTester}
import org.specs2.mutable.Specification

class CardinalityModuleSpec extends Specification {

  object build extends TestRootModule {

    object foo extends CardinalityModule {
      def scalaVersion = "3.9.0"
    }

    object old extends CardinalityModule {
      def scalaVersion = "3.3.7"
      override def moduleDir = foo.moduleDir
    }

    lazy val millDiscover = Discover[this.type]
  }

  private val fixture = os.Path(sys.props("user.dir")) / "src" / "test" / "resources" / "fixture"

  // One testkit session for every example: a session sets up `build`'s directory and two cannot
  // share it.
  "the Mill plugin" should {
    "write a module's report (a Boolean and an Option[Boolean] make 2 * 3 = 6; the compiler's " +
      "(Boolean, Boolean) = 4), on two Scala versions other than the calculator's: its jars are " +
      "resolved apart from the module; refuse a source without compiled classes; seed the skill with Mill " +
      "commands, refresh its own file and refuse a user's" in {
        UnitTester(build, fixture).scoped { eval =>
          val Right(same) = eval(build.foo.cardinalityReport()): @unchecked
          val Right(other) = eval(build.old.cardinalityReport()): @unchecked
          val uncompiled = Leftover((fixture / "foo" / "src" / "P.scala").toString)
          val Right(seeded) = eval(build.foo.cardinalitySeedSkill()): @unchecked
          val text = os.read(seeded.value.path)
          val Right(_) = eval(build.foo.cardinalitySeedSkill()): @unchecked
          os.write.over(seeded.value.path, text.replaceAll("(?s)<!-- Generated by.*?-->\\s*", ""))
          (os.read(same.value.path) must contain("6  P.<init>"))
            .and(os.read(same.value.path) must contain("4  Q.pair"))
            .and(os.read(other.value.path) must contain("6  P.<init>"))
            .and(eval(build.foo.cardinalityReportOf(uncompiled)).isLeft must beTrue)
            .and(text must contain("./mill foo.cardinalityReport"))
            .and(text must contain("Generated by mill-cardinality"))
            .and(text must not(contain("{{")))
            .and(eval(build.foo.cardinalitySeedSkill()).isLeft must beTrue)
        }
      }
  }

}
