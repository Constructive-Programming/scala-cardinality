package cardinality.reporting

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Path}

/** The cardinality-reduction skill a build tool plugin seeds into its user's repository: one
  * template, shared by the sbt and Mill plugins, with the build tool's command lines filled in.
  */
object Skill {

  /** The build tool a skill is seeded for, with the lines that differ between them. */
  enum Tool(
      val plugin: String,
      val seedCommand: String,
      val reportCommand: String,
      val reportFile: String,
      val selectedCommand: String,
      val reportOfCommand: String,
      val baseline: String
  ) {

    case Sbt
        extends Tool(
          "sbt-cardinality",
          "cardinalitySeedSkill",
          "sbt cardinalityReport",
          "cardinalityReportFile (default: target/cardinality/report.txt)",
          "sbt 'cardinalityReportSelected <qualified.Name>'",
          "sbt 'cardinalityReportOf <path-or-jar>'",
          "point `cardinalityReportFile` at a path under version control or copy the report there"
        )

    case Mill
        extends Tool(
          "mill-cardinality",
          "<module>.cardinalitySeedSkill",
          "./mill __.cardinalityReport",
          "out/<module>/cardinalityReport.dest/report.txt",
          "./mill <module>.cardinalityReportSelected <qualified.Name>",
          "./mill <module>.cardinalityReportOf <path-or-jar>",
          "copy `report.txt` from the command's `out/` directory to a path under version control"
        )

  }

  // Every plugin's marker: a file any of them generated is refreshed by any of them, so a build
  // that moves between sbt and Mill keeps its seeded copy current.
  private val markers = Tool.values.map(tool => s"Generated by ${tool.plugin}")

  /** This library's version, read from its jar; both plugins are released with it. */
  def version: String =
    Option(getClass.getPackage.getImplementationVersion).getOrElse("(unversioned build)")

  /** The template, filled in for `tool` and the repository named `project`. */
  def render(tool: Tool, project: String): String = {
    val url = getClass.getResource("/cardinality/cardinality-reduction-skill.md")
    List(
      "{{tool}}" -> tool.plugin,
      "{{version}}" -> version,
      "{{project}}" -> project,
      "{{seedCommand}}" -> tool.seedCommand,
      "{{reportCommand}}" -> tool.reportCommand,
      "{{reportFile}}" -> tool.reportFile,
      "{{selectedCommand}}" -> tool.selectedCommand,
      "{{reportOfCommand}}" -> tool.reportOfCommand,
      "{{baseline}}" -> tool.baseline
    ).foldLeft(new String(url.openStream().readAllBytes(), UTF_8)) {
      case (text, (key, value)) =>
        text.replace(key, value)
    }
  }

  /** Writes the skill to `output`. The marker comment is the ownership check: a file a plugin
    * generated is refreshed, one it did not is refused (`Left`), because a user's edits to their
    * copy must never be silently clobbered. `Right` says what was done.
    */
  def seed(tool: Tool, output: Path, project: String): Either[String, String] = {
    val skill = render(tool, project)
    val existing = Option.when(Files.exists(output))(Files.readString(output, UTF_8))
    existing match {
      case Some(text) if !markers.exists(text.contains) =>
        Left(
          s"$output exists and was not generated by ${tool.plugin}; move or delete it to seed a fresh copy"
        )
      case Some(text) if text == skill => Right(s"skill already up to date: $output")
      case _                           =>
        Files.createDirectories(output.toAbsolutePath.getParent)
        Files.writeString(output, skill, UTF_8)
        Right(s"seeded the cardinality-reduction skill: $output")
    }
  }

}
