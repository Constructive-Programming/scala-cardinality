package cardinality.reporting

import cardinality.reporting.Skill.Tool
import java.nio.file.{Files, Path}
import org.specs2.mutable.Specification

/** The seeded skill: one template filled in per build tool, refreshed while generated, never
  * written over once a user owns it.
  */
class SkillSpec extends Specification {

  private def target: Path =
    cardinality.Compiled.temporary("skill").resolve(".claude/skills/cardinality-reduction/SKILL.md")

  "render" should {
    "fill in every placeholder, with each tool's own commands" in {
      val sbt = Skill.render(Tool.Sbt, "demo")
      val mill = Skill.render(Tool.Mill, "demo")
      (sbt must not(contain("{{")))
        .and(mill must not(contain("{{")))
        .and(sbt must contain("# Cardinality reduction in demo"))
        .and(sbt must contain("sbt cardinalityReport"))
        .and(sbt must contain("Generated by sbt-cardinality"))
        .and(mill must contain("./mill __.cardinalityReport"))
        .and(mill must contain("./mill <module>.cardinalityReportSelected <qualified.Name>"))
        .and(mill must contain("out/<module>/cardinalityReport.dest/report.txt"))
        .and(mill must contain("Generated by mill-cardinality"))
        .and(mill must not(contain("sbt")))
    }
  }

  "seed" should {
    "write, then leave an up-to-date copy alone" in {
      val out = target
      val first = Skill.seed(Tool.Mill, out, "demo")
      val second = Skill.seed(Tool.Mill, out, "demo")
      (first must beRight(startWith("seeded")))
        .and(second must beRight(startWith("skill already up to date")))
        .and(Files.readString(out) === Skill.render(Tool.Mill, "demo"))
    }

    "refresh a copy either plugin generated" in {
      val out = target
      Skill.seed(Tool.Sbt, out, "demo")
      (Skill.seed(Tool.Mill, out, "demo") must beRight(startWith("seeded")))
        .and(Files.readString(out) === Skill.render(Tool.Mill, "demo"))
    }

    "refuse to overwrite a file it did not generate" in {
      val out = target
      Files.createDirectories(out.getParent)
      Files.writeString(out, "my own skill")
      (Skill.seed(Tool.Sbt, out, "demo") must beLeft(contain("not generated by sbt-cardinality")))
        .and(Files.readString(out) === "my own skill")
    }
  }

}
